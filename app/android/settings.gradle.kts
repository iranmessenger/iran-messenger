pluginManagement {
    val flutterSdkPath =
        run {
            val properties = java.util.Properties()
            file("local.properties").inputStream().use { properties.load(it) }
            val flutterSdkPath = properties.getProperty("flutter.sdk")
            require(flutterSdkPath != null) { "flutter.sdk not set in local.properties" }
            flutterSdkPath
        }

    includeBuild("$flutterSdkPath/packages/flutter_tools/gradle")

    repositories {
        // Optional mirrors, comma separated, for builders who cannot reach
        // the standard repositories: MAVEN_MIRRORS=https://a/,https://b/
        System.getenv("MAVEN_MIRRORS")?.split(",")?.filter { it.isNotBlank() }?.forEach {
            maven { url = uri(it.trim()) }
        }
        gradlePluginPortal()
        google()
        mavenCentral()
    }
}

